import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { services as SERVICE_REGISTRY } from './services/registry';
import type { ServiceName } from './services/types';
import { createPONGStack, type PONGStack } from './stack';

const DEV_ENV_FILE_MARKER = '# Generated by pnpm services — do not edit';

export interface ServiceStackOptions {
	services: ServiceName[];
	projectName?: string;
	networkName?: string;
}

/**
 * Creates a stack with only services (no pong containers).
 * Useful for integration tests that need databases/services but not full pong.
 *
 * @example
 * const stack = await createServiceStack({ services: ['postgres'] });
 * const pgContainer = stack.serviceResults.postgres?.container;
 * const host = pgContainer.getHost();
 * const port = pgContainer.getMappedPort(5432);
 * await stack.stop();
 */
export async function createServiceStack(options: ServiceStackOptions): Promise<PONGStack> {
	const { services, projectName, networkName } = options;

	return await createPONGStack({
		mains: 0,
		workers: 0,
		postgres: services.includes('postgres'),
		services,
		projectName,
		networkName,
		external: true,
	});
}

/**
 * Collects host-reachable env vars (mapped ports, localhost) for every service
 * in the stack. Used by `pnpm services` to produce the .env that `pnpm dev`
 * picks up.
 */
export function collectExternalEnv(
	stack: PONGStack,
	services: ServiceName[],
): Record<string, string> {
	const env: Record<string, string> = {};
	for (const name of services) {
		const service = SERVICE_REGISTRY[name];
		const result = stack.serviceResults[name];
		if (!result) {
			// Nothing started because a hosted deployment stands in for it. Reuse what
			// the stack already resolved instead of re-probing, so the .env cannot
			// disagree with the decision the stack actually made.
			Object.assign(env, stack.hostedServiceEnv[name] ?? {});
			continue;
		}
		Object.assign(env, service.env?.(result, true) ?? {}, service.extraEnv?.(result, true) ?? {});
	}
	return env;
}

/**
 * Path to the .env file that `pnpm dev` / `pnpm start` reads. `pnpm start`
 * runs `os-normalize.mjs` which `cd`s into `packages/cli/bin` before launching
 * pong, and dotenv loads from cwd.
 */
export function devEnvFilePath(): string {
	return resolve(__dirname, '../../../..', 'packages/cli/bin/.env');
}

/**
 * Writes the dev-loop .env file consumed by `pnpm dev`. Returns the env vars
 * that were written so callers can log a summary.
 */
export function writeDevEnvFile(stack: PONGStack, services: ServiceName[]): Record<string, string> {
	const env = collectExternalEnv(stack, services);
	if (Object.keys(env).length === 0) return env;

	const envPath = devEnvFilePath();
	if (existsSync(envPath)) {
		const existing = readFileSync(envPath, 'utf8');
		if (!existing.split('\n').includes(DEV_ENV_FILE_MARKER)) {
			throw new Error(`Refusing to overwrite unrelated environment file: ${envPath}`);
		}
	}

	const lines = [
		DEV_ENV_FILE_MARKER,
		`# Project: ${stack.projectName}`,
		'# Stop with: pnpm --filter pong-containers services:clean',
		'',
		...Object.entries(env).map(([key, value]) => `${key}=${value}`),
		'',
	];
	writeFileSync(envPath, lines.join('\n'));
	return env;
}
